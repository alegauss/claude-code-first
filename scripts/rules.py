"""The machine-readable rule registry: build it from the chapters, check it, query it.

The chapters (spec/XX.md) are the normative text. spec/rules.toml is generated from
them, so the two cannot disagree: `--check` fails when the file is stale, and CI runs
it. TOML, because a person reads it; it is still never edited by hand.

    python scripts/rules.py build            write spec/rules.toml
    python scripts/rules.py build --check    exit 1 if spec/rules.toml is stale
    python scripts/rules.py query [filters]  list matching rules without reading chapters

Filters combine with AND: --level 2, --keyword MUST, --chapter VG, --checked automatically
(or "by judgement"), --harness H10, --finding F301. Example: which level 2 rules are not
automated?  python scripts/rules.py query --level 2 --checked "by judgement"

Run from the repository root.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

SPEC = Path("spec")
REGISTRY = SPEC / "rules.toml"
CHAPTER = re.compile(r"^[A-Z]{2}\.md$")
HEADING = re.compile(r"^### ([A-Z]{2}-\d+) (.+)$")
SENTENCE = re.compile(r"^\*\*(.+)\*\*\s*$")
ROW = re.compile(r"^\|\s*([^|]+?)\s*\|\s*(.*?)\s*\|\s*$")
IDS = re.compile(r"\b([FH]\d+|O\d+)\b")


def parse(root: Path) -> list[dict]:
    """Every rule in the chapter files, in address order."""
    rules = []
    for path in sorted((root / SPEC).iterdir()):
        if not CHAPTER.match(path.name):
            continue
        lines, fenced, current = path.read_text(encoding="utf-8").splitlines(), False, None
        for line in lines:
            if line.lstrip().startswith("```"):
                fenced = not fenced
                continue
            if fenced:
                continue
            heading = HEADING.match(line)
            if heading:
                current = {"address": heading.group(1), "chapter": path.stem, "title": heading.group(2)}
                rules.append(current)
                continue
            if current is None:
                continue
            sentence = SENTENCE.match(line)
            if sentence and "statement" not in current:
                current["statement"] = " ".join(sentence.group(1).replace("*", "").split())
                continue
            row = ROW.match(line)
            if row and row.group(1) in ("Keyword", "Level", "Checked", "Findings", "Harness facts", "Status"):
                name, value = row.group(1), row.group(2)
                if name in ("Findings", "Harness facts"):
                    current["findings" if name == "Findings" else "harness"] = IDS.findall(value)
                else:
                    current[name.lower()] = value
    def order(rule):
        return (rule["address"][:2], int(rule["address"].split("-")[1]))
    return sorted(rules, key=order)


def toml_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(rules: list[dict]) -> str:
    out = [
        "# Generated by `python scripts/rules.py build` from the chapters in spec/.",
        "# Do not edit: the chapters are the normative text, and CI fails when this file",
        "# disagrees with them. `detector` names the script that decides the rule",
        "# automatically, where one exists.",
    ]
    for rule in rules:
        out += [
            "",
            "[[rule]]",
            f"address = {toml_string(rule['address'])}",
            f"chapter = {toml_string(rule['chapter'])}",
            f"title = {toml_string(rule['title'])}",
            f"keyword = {toml_string(rule.get('keyword', ''))}",
            f"level = {toml_string(rule.get('level', ''))}",
            f"statement = {toml_string(rule.get('statement', ''))}",
            f"checked = {toml_string(rule.get('checked', ''))}",
            f"detector = {toml_string(rule.get('detector', ''))}",
            "findings = [" + ", ".join(toml_string(f) for f in rule.get("findings", [])) + "]",
            "harness = [" + ", ".join(toml_string(h) for h in rule.get("harness", [])) + "]",
            f"status = {toml_string(rule.get('status', ''))}",
        ]
    return "\n".join(out) + "\n"


def problems_in(rules: list[dict]) -> list[str]:
    problems = []
    seen = set()
    for rule in rules:
        address = rule["address"]
        if address in seen:
            problems.append(f"{address} is defined twice")
        seen.add(address)
        for field in ("statement", "keyword", "level", "checked", "status"):
            if not rule.get(field):
                problems.append(f"{address} has no {field}")
        if not rule.get("findings"):
            problems.append(f"{address} cites no finding")
        if rule.get("keyword") and rule["keyword"] not in rule.get("statement", ""):
            problems.append(f"{address}: keyword {rule['keyword']} is not in its normative sentence")
    return problems


def build(root: Path, check: bool) -> int:
    rules = parse(root)
    problems = problems_in(rules)
    for problem in problems:
        print(problem)
    text = render(rules)
    target = root / REGISTRY
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"{REGISTRY.as_posix()} is out of date: run python scripts/rules.py build")
            return 1
    else:
        target.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(rules)} rule(s)")
    return 1 if problems else 0


def query(root: Path, args: argparse.Namespace) -> int:
    rules = tomllib.loads((root / REGISTRY).read_text(encoding="utf-8"))["rule"]
    keep = [
        r for r in rules
        if (args.level is None or r["level"] == args.level)
        and (args.keyword is None or r["keyword"] == args.keyword)
        and (args.chapter is None or r["chapter"] == args.chapter)
        and (args.checked is None or r["checked"] == args.checked)
        and (args.harness is None or args.harness in r["harness"])
        and (args.finding is None or args.finding in r["findings"])
    ]
    for r in keep:
        print(f"{r['address']:6} {r['keyword']:10} L{r['level']:8} {r['statement']}")
    print(f"{len(keep)} of {len(rules)} rule(s)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", default=".")
    sub = parser.add_subparsers(dest="command", required=True)
    b = sub.add_parser("build")
    b.add_argument("--check", action="store_true")
    q = sub.add_parser("query")
    for name in ("level", "keyword", "chapter", "checked", "harness", "finding"):
        q.add_argument(f"--{name}")
    args = parser.parse_args(argv)
    root = Path(args.root)
    return build(root, args.check) if args.command == "build" else query(root, args)


if __name__ == "__main__":
    sys.exit(main())
