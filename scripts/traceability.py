"""The traceability gate: every rule traces to graded findings, and every finding to sources.

Fails when:
  - a rule cites no finding, or a finding that does not exist or is withdrawn;
  - a rule's keyword is stronger than its best finding admits (evidence/grading.md):
    MUST and MUST NOT need a finding at R3 or above with S2 or above, or one at S3 or
    above; SHOULD and SHOULD NOT need one at S2 or above;
  - a finding carries no pointer to a primary source;
  - a finding is cited by no rule and no catalogue entry, and is not marked
    `| Use | background |` in its field table;
  - a catalogue entry links a rule address that does not exist.

The grading scale also lowers a keyword for contested findings; that judgement is left to
review, and this gate checks only the ceiling. It writes spec/traceability.md, the matrix
from rule to findings to the projects their pointers reach, and `--check` fails when that
file is stale. Run from the repository root.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import rules as registry  # noqa: E402
from index_findings import FINDINGS, parse as parse_finding  # noqa: E402
from resolve_citations import POINTER, prose  # noqa: E402

MATRIX = Path("spec/traceability.md")
CATALOGUE = Path("spec/catalogue")
RULE_LINK = re.compile(r"\[([A-Z]{2}-\d+)\]\((?:\.\./)+[A-Z]{2}\.md")
GRADE = re.compile(r"R([1-4])/S([1-4])")
USE = re.compile(r"^\|\s*Use\s*\|\s*background\s*\|", re.MULTILINE)


def admits(keyword: str, grades: list[tuple[int, int]]) -> bool:
    """Whether the best of these grades admits the keyword."""
    if keyword.startswith("MUST"):
        return any((r >= 3 and s >= 2) or s >= 3 for r, s in grades)
    if keyword.startswith("SHOULD"):
        return any(s >= 2 for r, s in grades)
    return True


def load_findings(root: Path) -> dict[str, dict]:
    findings = {}
    for path in (root / FINDINGS).glob("F*.md"):
        finding, _ = parse_finding(path)
        if not finding:
            continue
        text = path.read_text(encoding="utf-8")
        grade = GRADE.match(finding.get("Grade", ""))
        pointers = [m["project"] for m in POINTER.finditer(prose(text))]
        findings[f"F{finding['number']}"] = {
            "grade": (int(grade.group(1)), int(grade.group(2))) if grade else (0, 0),
            "label": finding.get("Grade", "?"),
            "status": finding.get("Status"),
            "pointers": len(pointers),
            "projects": sorted(set(pointers)),
            "background": bool(USE.search(text)),
        }
    return findings


def audit(root: Path) -> tuple[list[str], list[dict], dict]:
    rules = registry.parse(root)
    findings = load_findings(root)
    addresses = {r["address"] for r in rules}
    cited = set()
    problems = []
    for rule in rules:
        address, keyword = rule["address"], rule.get("keyword", "")
        ids = rule.get("findings", [])
        if not ids:
            problems.append(f"{address}: cites no finding")
        for fid in ids:
            cited.add(fid)
            if fid not in findings:
                problems.append(f"{address}: cites {fid}, which does not exist")
            elif findings[fid]["status"] != "active":
                problems.append(f"{address}: cites {fid}, which is withdrawn")
        grades = [findings[f]["grade"] for f in ids if f in findings and findings[f]["status"] == "active"]
        if ids and not admits(keyword, grades):
            best = ", ".join(findings[f]["label"] for f in ids if f in findings)
            problems.append(f"{address}: {keyword} is stronger than its findings admit ({best})")
    for entry in sorted((root / CATALOGUE).glob("*/*.md")):
        text = entry.read_text(encoding="utf-8")
        cited.update(re.findall(r"\bF\d+\b", text.split("\n## Related", 1)[-1]))
        for address in RULE_LINK.findall(text):
            if address not in addresses:
                problems.append(f"{entry.relative_to(root).as_posix()}: links {address}, which is not a rule")
    for fid, finding in sorted(findings.items(), key=lambda kv: int(kv[0][1:])):
        if finding["status"] != "active":
            continue
        if finding["pointers"] == 0:
            problems.append(f"{fid}: carries no pointer to a primary source")
        if fid not in cited and not finding["background"]:
            problems.append(f"{fid}: is cited by no rule or catalogue entry and not marked background")
    return problems, rules, findings


def render(rules: list[dict], findings: dict) -> str:
    out = [
        "# Traceability matrix",
        "",
        "Generated by `python scripts/traceability.py` from the chapters and the findings register;",
        "do not edit by hand. Each rule, the findings it rests on with their grades, and the",
        "corpus projects those findings' pointers reach. Follow a finding to its observations,",
        "and each observation to its pinned source.",
        "",
        "| Rule | Keyword | Level | Findings | Projects reached | Pointers |",
        "|---|---|---|---|---|---|",
    ]
    for rule in rules:
        ids = [f for f in rule.get("findings", []) if f in findings]
        cells = ", ".join(f"[{f}](../evidence/findings/{f}.md) {findings[f]['label']}" for f in ids)
        projects = sorted({p for f in ids for p in findings[f]["projects"]})
        count = sum(findings[f]["pointers"] for f in ids)
        out.append(
            f"| {rule['address']} | {rule.get('keyword', '')} | {rule.get('level', '')} | {cells} "
            f"| {', '.join(projects)} | {count} |"
        )
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the matrix is stale")
    parser.add_argument("--root", default=".")
    args = parser.parse_args(argv)
    root = Path(args.root)
    problems, rules, findings = audit(root)
    for problem in problems:
        print(problem)
    text = render(rules, findings)
    target = root / MATRIX
    stale = not target.exists() or target.read_text(encoding="utf-8") != text
    if args.check and stale:
        print(f"{MATRIX.as_posix()} is out of date: run python scripts/traceability.py")
    elif not args.check:
        target.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(rules)} rule(s), {len(findings)} finding(s), {len(problems)} problem(s)")
    return 1 if problems or (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
