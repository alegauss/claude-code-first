"""Generate evidence/findings/index.md from the finding files, or check it is current.

Each finding file `evidence/findings/F<n>.md` opens with a title line and a field table
(see evidence/findings/README.md). This script reads the title and the Status, Topic,
Grade, Cases and Contrary fields, and writes an index grouped by topic, strongest grade
first, with withdrawn findings listed apart. It also refuses a finding whose table is
missing a field, whose grade is not R1-R4/S1-S4, or whose number lies outside its
topic's block.

    python scripts/index_findings.py           write the index
    python scripts/index_findings.py --check   exit 1 if the index is stale or a finding is malformed

Run from the repository root.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

FINDINGS = Path("evidence/findings")
INDEX = FINDINGS / "index.md"
TOPICS = {
    "Context economy and agent prose": range(1, 100),
    "Planning, recording, and what the person decides": range(100, 200),
    "Commits and concurrent sessions": range(200, 300),
    "Gates, verification, and hooks against instructions": range(300, 400),
    "Environment, permissions, and agent-facing products": range(400, 500),
}
FIELDS = ("Status", "Topic", "Grade", "Cases", "Contrary", "Harness facts")
TITLE = re.compile(r"^# F(\d+) (.+)$")
ROW = re.compile(r"^\|\s*([^|]+?)\s*\|\s*(.*?)\s*\|\s*$")
GRADE = re.compile(r"^R([1-4])/S([1-4])$")


def parse(path: Path) -> tuple[dict | None, list[str]]:
    """The finding's fields, and the problems found in it."""
    lines = path.read_text(encoding="utf-8-sig").splitlines()
    problems = []
    title = TITLE.match(lines[0]) if lines else None
    if not title:
        return None, [f"{path.as_posix()}: first line is not '# F<n> <claim>'"]
    number = int(title.group(1))
    if path.stem != f"F{number}":
        problems.append(f"{path.as_posix()}: title names F{number}")
    fields = {}
    for line in lines[1:]:
        if line.startswith("## "):
            break
        row = ROW.match(line)
        if row and row.group(1) in FIELDS:
            fields[row.group(1)] = row.group(2)
    for name in FIELDS:
        if name not in fields:
            problems.append(f"{path.as_posix()}: no {name} field")
    grade = GRADE.match(fields.get("Grade", ""))
    if "Grade" in fields and not grade:
        problems.append(f"{path.as_posix()}: grade {fields['Grade']!r} is not R1-R4/S1-S4")
    topic = fields.get("Topic")
    if topic is not None and topic not in TOPICS:
        problems.append(f"{path.as_posix()}: topic {topic!r} is not one of the declared topics")
    elif topic is not None and number not in TOPICS[topic]:
        problems.append(f"{path.as_posix()}: F{number} lies outside the block of {topic!r}")
    if fields.get("Status") not in (None, "active", "withdrawn"):
        problems.append(f"{path.as_posix()}: status must be active or withdrawn")
    finding = {
        "number": number,
        "claim": title.group(2),
        "file": path.name,
        "rank": (-int(grade.group(1)), -int(grade.group(2))) if grade else (0, 0),
        **fields,
    }
    return finding, problems


def render(findings: list[dict]) -> str:
    active = [f for f in findings if f.get("Status") == "active"]
    withdrawn = [f for f in findings if f.get("Status") == "withdrawn"]
    out = [
        "# Findings index",
        "",
        "Generated by `python scripts/index_findings.py` from the finding files; do not edit",
        "by hand. Within each topic, findings are listed strongest grade first.",
        "",
        f"{len(active)} active, {len(withdrawn)} withdrawn.",
    ]
    for topic in TOPICS:
        rows = sorted((f for f in active if f["Topic"] == topic), key=lambda f: (f["rank"], f["number"]))
        if not rows:
            continue
        out += ["", f"## {topic}", "", "| Finding | Grade | Claim | Cases | Contrary |", "|---|---|---|---|---|"]
        out += [
            f"| [F{f['number']}]({f['file']}) | {f['Grade']} | {f['claim']} | {f['Cases']} | {f['Contrary']} |"
            for f in rows
        ]
    if withdrawn:
        out += ["", "## Withdrawn", "", "| Finding | Claim |", "|---|---|"]
        out += [f"| [F{f['number']}]({f['file']}) | {f['claim']} |" for f in sorted(withdrawn, key=lambda f: f["number"])]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the index is stale")
    parser.add_argument("--root", default=".", help="the repository root")
    args = parser.parse_args(argv)

    folder = Path(args.root) / FINDINGS
    findings, problems = [], []
    for path in sorted(folder.glob("F*.md"), key=lambda p: int(re.sub(r"\D", "", p.stem) or 0)):
        finding, found = parse(path)
        problems += found
        if finding:
            findings.append(finding)
    numbers = [f["number"] for f in findings]
    for n in sorted({n for n in numbers if numbers.count(n) > 1}):
        problems.append(f"F{n} is defined more than once")

    for problem in problems:
        print(problem)
    text = render(findings)
    index = Path(args.root) / INDEX
    if args.check:
        current = index.read_text(encoding="utf-8") if index.exists() else ""
        if current != text:
            print(f"{INDEX.as_posix()} is out of date: run python scripts/index_findings.py")
            return 1
        return 1 if problems else 0
    index.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(findings)} finding(s) indexed")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
